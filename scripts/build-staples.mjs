// Builds src/staples-data.js, the basic foods food search lists first
// (src/staples.js), from USDA FoodData Central SR Legacy (public domain) and
// the hand-made list scripts/staples.txt (Czech and English name, the USDA
// food, its usual portion).
//   curl -O https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_json_2018-04.zip && unzip it
//   node scripts/build-staples.mjs FoodData_Central_sr_legacy_food_json_2018-04.json
import { readFileSync, writeFileSync } from "node:fs";

const [source] = process.argv.slice(2);
if (!source) throw new Error("usage: node scripts/build-staples.mjs <FoodData_Central_sr_legacy_food_json.json>");
const foods = JSON.parse(readFileSync(source, "utf8")).SRLegacyFoods;
const FL_OZ = 29.5735;
const round = (v, d = 2) => v == null ? undefined : Math.round(v * 10 ** d) / 10 ** d;

const out = [], problems = [];
for (const line of readFileSync(new URL("./staples.txt", import.meta.url), "utf8").split("\n")) {
  if (!line.trim() || line.startsWith("#")) continue;
  const [cs, en, pattern, portion = "", pcs = "", pen = "", ml = ""] = line.split("|").map(s => s.trim());
  const wanted = pattern.toLowerCase();
  const food = foods.find(f => f.description.toLowerCase() === wanted) || foods.find(f => f.description.toLowerCase().startsWith(wanted));
  if (!food) { problems.push(`no USDA food: ${cs} (${pattern})`); continue; }
  const amount = n => food.foodNutrients.find(x => x.nutrient.number === n && (n !== "208" || x.nutrient.unitName === "kcal"))?.amount;
  const portions = food.foodPortions || [];
  const named = p => `${p.modifier || ""} ${p.measureUnit?.name || ""}`.toLowerCase();
  // Drinks are counted in ml: grams per ml from the fl oz or cup weight.
  const flOz = portions.find(p => /fl oz/.test(named(p)) && p.gramWeight);
  const cup = portions.find(p => /^cup\b/.test(named(p).trim()) && p.gramWeight);
  const density = !ml ? 1 : flOz ? flOz.gramWeight / ((flOz.amount || 1) * (/(\d+(\.\d+)?) fl oz/.exec(named(flOz))?.[1] || 1) * FL_OZ)
    : cup ? cup.gramWeight / ((cup.amount || 1) * 8 * FL_OZ) : 1;
  let size = null;
  if (portion.startsWith("=")) size = Number(portion.slice(1));
  else if (portion) {
    const p = portions.find(p => named(p).includes(portion.toLowerCase()));
    if (!p) { problems.push(`no portion "${portion}": ${cs}`); continue; }
    size = p.gramWeight / (p.amount || 1) / (ml ? density : 1);
  }
  const per100 = v => v == null ? undefined : round(v * density);
  const sodium = amount("307");
  const r = { k: `usda_sr_legacy:${food.fdcId}`, cs, en };
  if (ml) r.u = "ml";
  Object.assign(r, { e: per100(amount("208")) ?? 0, p: per100(amount("203")) ?? 0, c: per100(amount("205")) ?? 0, f: per100(amount("204")) ?? 0 });
  const su = per100(amount("269")), fi = per100(amount("291")), sa = sodium == null ? undefined : round(sodium * density * 2.5 / 1000);
  if (su != null) r.su = su; if (fi != null) r.fi = fi; if (sa != null) r.sa = sa;
  if (size) r.s = [Math.round(size), pcs, pen];
  out.push(r);
}
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
const rows = out.map(r => "  " + JSON.stringify(r)).join(",\n");
writeFileSync(new URL("../src/staples-data.js", import.meta.url),
  `// Generated by scripts/build-staples.mjs from scripts/staples.txt and USDA FoodData Central SR Legacy\n` +
  `// (public domain). Values per 100 g, or per 100 ml with u: "ml"; s: [portion size, Czech name, English name].\n` +
  `export const STAPLES = [\n${rows}\n];\n`);
console.log(`${out.length} basic foods`);
